// ModelForType returns the HOMELAB model prefix for a sensor type.
func ModelForType(sensorType string) string {
	switch sensorType {
	case "DWS":
		return "HOMELABDWS00ACFD"
	case "PIR":
		return "HOMELABPIR00ACFD"
	case "KPD":
		return "HOMELABKPD00ACFD"
	case "SRN":
		return "HOMELABSRN00BCFD"
	default:
		return ""
	}
}

// BytecodeChunks returns the managed frame payloads for a sensor model.
// The model is extracted from the beacon (e.g. "HOMELABDWS00ACFD" → "HOMELABDWS").
// DWS and PIR have verified chunks from tcpdump captures.
func BytecodeChunks(model string) ([][]byte, bool) {
	if len(model) < 10 {
		return nil, false
	}
	prefix := model[:10]
	switch prefix {
	case "HOMELABDWS":
		return dwsChunks, true
	case "HOMELABPIR":
		return pirChunks, true
	case "HOMELABSRN":
		return srnChunks, true
	case "HOMELABKPD":
		return kpdChunks, true
	default:
		return nil, false
	}
}

